export function createHeadless() {
  const deferred = [];
  const ctx = new Proxy({}, { get: (o,k) => o[k] || (k === 'measureText' ? () => ({width:0}) : k.startsWith('create') ? () => ({addColorStop:noop}) : noop) });
  const element = () => new Proxy({ style:{},dataset:{},children:[],classList:{add:noop,remove:noop,toggle:noop},getContext:()=>ctx,querySelector:()=>null,querySelectorAll:()=>[],getBoundingClientRect:()=>({height:0,top:0}),appendChild:noop }, {get:(o,k)=>o[k] ?? noop});
  const document = { scripts:[],head:element(),body:element(),createElement:element,querySelector:()=>null,querySelectorAll:()=>[],getElementById:()=>null,addEventListener:(t,f)=>{if(t==='DOMContentLoaded')deferred.push(f);} };
  const G = {headless:true};
  G.platform = {document,window:{G,addEventListener:noop},Image:class{constructor(){this.complete=false;this.naturalWidth=0;}addEventListener(){}},localStorage:{getItem:()=>null,setItem:noop,removeItem:noop},setTimeout:(f,ms)=>{if(!ms)deferred.push(f);return 0;},setInterval:()=>0};
  const sprite = (kind, ...args) => ({img:null,w:24,h:24,kind,args});
  G.SPR = new Proxy({mk:(w,h)=>[{width:w,height:h,getContext:()=>ctx},ctx],lookFor:cls=>({cls}),crisp:noop}, {get:(o,k)=>o[k] || ((...args)=>sprite(k,...args))});
  G.VFX = new Proxy({parts:[],fx:[],X:{}}, {get:(o,k)=>o[k] || noop});
  G.VFX.update=()=>{G.VFX.parts.length=G.VFX.fx.length=0;};
  G.FX = new Proxy({T:new Proxy({}, {get:()=>Array(25).fill('spark')}),M:{},ICONX:{}}, {get:(o,k)=>o[k] || noop});
  G.FX6={mini:noop,REC:{},PAL:{}}; G.TX=new Proxy({}, {get:()=>noop});
  const panels=new Proxy({}, {get:(o,k)=>o[k] ||= {tabs:[],render:()=>'',after:noop}});
  G.UI=new Proxy({PANELS:panels,esc:x=>String(x??''),ICONS:{W:{},ARM:{}},ICONKIT:{make:noop}}, {get:(o,k)=>o[k] || noop});
  const names=['data','skills25','engine','riders','systems','modes','items2','classset','inv2','costume','passives','setult2','elements','botpower','boss_manifest','bosses','wboss2','deco_manifest','city','mon_manifest','monsters48','classmech','items3','dungeon2','enh2','noquest','vault','forge','jobs','fash2','gacha2','fashaura','petart','fashfx','balance','tickreq'];
  for(const name of names) { try {globalThis.ASHFALL_SIM_FACTORIES[name](G);}catch(e){throw new Error(name+': '+e.message,{cause:e});} }
  for(const fn of deferred) fn();
  G.E.renderMapCanvas=noop; G.E.vis=()=>false; G.E.spriteInfo=()=>({img:null,sx:0,sy:0,w:24,h:24,sc:1});
  const generated = G.S.genItem; G.S.genItem = (...args) => { const item=generated(...args); if(item)item.uid=crypto.randomUUID(); return item; };
  G.UI.itemIcon=noop;G.UI.petIcon=noop;G.UI.mcIcon=noop;
  G.S.persist=noop; G.S.onLevel=noop;
  return G;
}
